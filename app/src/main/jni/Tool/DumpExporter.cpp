    static std::string SanitizeIdentifier(const std::string &str)
    {
        std::string res = str;
        for (char &c : res)
        {
            if (c == '.' || c == '/' || c == '`' || c == '<' || c == '>' || c == '$' || c == ' ')
                c = '_';
        }
        return res;
    }

    bool ExportDumpCs(const std::string &outPath, ProgressCallback cb)
    {
        return Il2cpp::Dump(outPath, [cb](const Il2cpp::DumpProgress &p) {
            if (cb)
            {
                ExportProgress ep;
                ep.progress = p.progress;
                ep.currentItem = p.currentAssembly;
                ep.currentClass = p.currentClassIndex;
                ep.totalClasses = p.totalClasses;
                cb(ep);
            }
        });
    }

    bool ExportIdaScript(const std::string &outPath, ProgressCallback cb)
    {
        std::ofstream ofs(outPath);
        if (!ofs.is_open())
        {
            LOGE("DumpExporter: Could not open output file %s", outPath.c_str());
            return false;
        }

        ofs << "# IDA Pro Python Rename Script for MLBB 2.2.16 (SOSplit)\n";
        ofs << "# Generated by Android-LibTool-New\n\n";
        ofs << "import idaapi, idc\n\n";
        ofs << "base = idaapi.get_imagebase()\n";
        ofs << "print('[*] Renaming MLBB SOSplit symbols...')\n";
        ofs << "count = 0\n\n";

        size_t total = g_Methods.size();
        std::unordered_set<uintptr_t> seenRVAs;

        for (size_t i = 0; i < total; ++i)
        {
            MethodInfo *m = g_Methods[i];
            if (!m || !m->methodPointer)
                continue;

            uintptr_t rva = m->getAbsAddress();
            if (rva == 0 || seenRVAs.count(rva))
                continue;
            seenRVAs.insert(rva);

            std::string mod = m->getModuleName();
            std::string className = m->getClass() ? m->getClass()->getName() : "UnknownClass";
            std::string methodName = m->getName() ? m->getName() : "UnknownMethod";
            std::string safeName = SanitizeIdentifier(className) + "__" + SanitizeIdentifier(methodName);

            ofs << "# Module: " << mod << "\n";
            ofs << "idc.set_name(base + 0x" << std::hex << std::uppercase << rva << ", '" << safeName << "', idc.SN_NOWARN)\n";
            ofs << "count += 1\n";

            if (cb && (i % 200 == 0 || i == total - 1))
            {
                ExportProgress ep;
                ep.progress = total > 0 ? (float)i / (float)total : 1.0f;
                ep.currentItem = safeName;
                ep.currentClass = (int)i;
                ep.totalClasses = (int)total;
                cb(ep);
            }
        }

        ofs << "\nprint(f'[+] Successfully renamed {count} symbols in IDA Pro.')\n";
        ofs.close();
        LOGI("DumpExporter: Exported IDA script to %s with %zu symbols", outPath.c_str(), seenRVAs.size());
        return true;
    }

